import React from "react";
import { AbsoluteFill, Sequence, staticFile } from "remotion";
import { Audio } from "@remotion/media";
import { C } from "./theme.ts";
import { BAR } from "./beat.ts";
import { TIMELINE } from "./timeline.ts";
import { Clone } from "./scenes/Clone.tsx";
import { Pile } from "./scenes/Pile.tsx";
import { Collapse } from "./scenes/Collapse.tsx";
import { Name } from "./scenes/Name.tsx";
import { Native } from "./scenes/Native.tsx";
import { Api } from "./scenes/Api.tsx";
import { Fleet } from "./scenes/Fleet.tsx";
import { Pack } from "./scenes/Pack.tsx";
import { Numbers } from "./scenes/Numbers.tsx";
import { End } from "./scenes/End.tsx";

type Scene = React.FC<{ dur: number }>;

const SCENES: Record<string, Scene> = {
  clone: Clone,
  pile: Pile,
  collapse: Collapse,
  name: Name,
  native: Native,
  api: Api,
  fleet: Fleet,
  pack: Pack,
  numbers: Numbers,
  end: End,
};

export const Perry: React.FC = () => (
  <AbsoluteFill style={{ backgroundColor: C.bg }}>
    {/* Generated by scripts/music.py at the same tempo the edit is cut to. */}
    <Audio src={staticFile("music/bed.mp3")} volume={0.8} />

    {TIMELINE.map((beat) => {
      const Scene = SCENES[beat.id];
      const dur = beat.length * BAR;
      return (
        <Sequence
          key={beat.id}
          name={`${beat.at} ${beat.id}`}
          from={beat.at * BAR}
          durationInFrames={dur}
          premountFor={20}
        >
          <Scene dur={dur} />
        </Sequence>
      );
    })}
  </AbsoluteFill>
);
